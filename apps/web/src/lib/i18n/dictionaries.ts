// Type-level: every locale must provide the exact same key shape.
void (fa satisfies Dictionary);

const dictionaries: Record<Locale, Dictionary> = { en, fa };

export function hasLocale(locale: string): locale is Locale {
  return locale === "en" || locale === "fa";
}

export function getDictionary(locale: Locale): Dictionary {
  return dictionaries[locale];
}

/** Localize a number: `1200` → `۱٬۲۰۰` in Persian. */
export function num(value: number | string, locale: Locale): string {
  const n = typeof value === "string" ? Number(value) : value;
  if (Number.isNaN(n)) return String(value);
  return new Intl.NumberFormat(locale === "fa" ? "fa-IR" : "en-US").format(n);
}

/** Fill `{name}` placeholders in a template. */
export function fill(
  template: string,
  vars: Record<string, number | string>,
  locale: Locale
): string {
  let output = template;
  for (const [key, value] of Object.entries(vars)) {
    output = output.replaceAll(
      `{${key}}`,
      typeof value === "number" ? num(value, locale) : value
    );
  }
  return output;
}

/**
 * Choose a singular/plural phrase and interpolate the count.
 * Persian dictionaries reuse the same phrase for both variants.
 */
export function plural(
  n: number,
  forms: { one: string; other: string },
  locale: Locale
): string {
  return fill(n === 1 ? forms.one : forms.other, { n }, locale);
}

